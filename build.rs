//! Cargo runs this build script before compiling the package. It puts two
//! things into the binaries:
//!
//! - the Windows application manifest `windows/slc-local-tts.manifest`
//!   (UTF-8 code page, themed message boxes, sharp display at any scale),
//!   in every binary, tests included. The manifest file explains each entry;
//! - the exe's icon and version details (product name, description,
//!   version), in the two programs.

use std::path::Path;

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR");
    let manifest = Path::new(&manifest_dir)
        .join("windows")
        .join("slc-local-tts.manifest");

    // `rustc-link-arg` (unlike `rustc-link-arg-bins`) applies to every binary
    // this package links, the test executables included, so the tests run
    // with the same code page as the real exe. rustc quotes each argument
    // for link.exe, so the spaces and `@` in the repo path are safe.
    //
    // /MANIFEST:EMBED puts the manifest inside the binary as a resource,
    // instead of a separate `.exe.manifest` file next to it; /MANIFESTINPUT
    // merges our file into the one link.exe generates (its UAC section).
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    println!("cargo:rerun-if-changed={}", manifest.display());
    println!("cargo:rerun-if-changed=build.rs");

    add_icon_and_version(Path::new(&manifest_dir));
}

/// Compiles the icon and version details into a Windows resource file and
/// links it into the programs. This needs the Windows SDK's resource
/// compiler (`rc.exe`), which Visual Studio installs.
///
/// It never sets a manifest: link.exe already makes the one manifest
/// resource above, and Windows allows only one (a second would be a
/// duplicate-resource link error).
fn add_icon_and_version(root: &Path) {
    let icon = root.join("assets").join("slc-local-tts.ico");
    println!("cargo:rerun-if-changed={}", icon.display());

    let mut resource = winresource::WindowsResource::new();
    resource
        .set("ProductName", "SLC Local TTS")
        .set("FileDescription", "SLC Local TTS");
    // The icon is generated by a test, which needs this build to run first;
    // without it the programs are built with Windows' default icon.
    if icon.is_file() {
        resource.set_icon(&icon.to_string_lossy());
    } else {
        println!(
            "cargo:warning=assets/slc-local-tts.ico is missing; run: cargo test --test icon_assets -- --ignored"
        );
    }
    if let Err(e) = resource.compile() {
        panic!(
            "couldn't compile the Windows resources (icon and version details): {e}. \
             The build needs the Windows SDK's rc.exe, which Visual Studio 2022 installs."
        );
    }
}
